/* =========================================================
   3. GENERATE ORDER ID
   ========================================================= */

function generateOrderId() {
    const date = new Date();

    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");

    const random = Math.floor(1000 + Math.random() * 9000);

    return `DGM-${year}${month}${day}-${random}`;
}


/* =========================================================
   4. GET SAVED ORDERS
   ========================================================= */

function getOrders() {
    return JSON.parse(localStorage.getItem("dzgm_orders") || "[]");
}


/* =========================================================
   5. SAVE ORDER
   ========================================================= */

function saveOrder(order) {
    const orders = getOrders();

    orders.unshift(order);

    localStorage.setItem(
        "dzgm_orders",
        JSON.stringify(orders)
    );
}


/* =========================================================
   6. CREATE ORDER
   ========================================================= */

function createOrder(type, product, price, customer = {}) {

    const order = {
        id: generateOrderId(),

        type: type,

        product: product,

        price: Number(price),

        customer: {
            name: customer.name || "",
            phone: customer.phone || "",
            email: customer.email || "",
            notes: customer.notes || ""
        },

        status: "pending",

        createdAt: new Date().toISOString()
    };

    saveOrder(order);

    return order;
}


/* =========================================================
   7. ORDER STATUS TRANSLATION
   ========================================================= */

function getStatusText(status) {

    const lang = localStorage.getItem("dzgm_language") || "ar";

    const map = {
        pending: "pending",
        confirmed: "confirmed",
        processing: "processing",
        completed: "completed",
        cancelled: "cancelled"
    };

    const key = map[status] || "pending";

    return translations[lang][key] || status;
}


