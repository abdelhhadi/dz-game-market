/* =========================================================
   14. FIX FEATURED FREE FIRE PRODUCT
   ========================================================= */

function fixFeaturedProducts() {

    const buttons =
        document.querySelectorAll(
            '[onclick*="openAccountOrder"]'
        );

    buttons.forEach(button => {

        const onclick =
            button.getAttribute("onclick");

        if (!onclick) return;

        if (onclick.includes("'Free Fire'")) {

            button.setAttribute(
                "onclick",
                "openAccountOrder('Free Fire Account #001', 1800)"
            );
        }

    });
}


