/* =========================================================
   11. COPY ORDER ID
   ========================================================= */

function copyOrderId(orderId) {

    const lang = localStorage.getItem("dzgm_language") || "ar";
    const t = translations[lang];

    navigator.clipboard.writeText(orderId)
        .then(() => {

            showToast(
                `${t.copied}: ${orderId}`,
                "success"
            );

        })
        .catch(() => {

            showToast(
                orderId,
                "success"
            );

        });
}


