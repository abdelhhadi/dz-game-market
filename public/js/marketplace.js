/* =========================================================
   RENDER ACCOUNTS
========================================================= */

function renderAccounts() {

    const grid =
        document.getElementById(
            "accountsGrid"
        );

    if (!grid) {
        return;
    }


    let result =
        [...accounts];


    const gameFilter =
        document.getElementById(
            "accountGameFilter"
        )?.value || "all";


    const search =
        document.getElementById(
            "accountSearch"
        )?.value
        ?.trim()
        .toLowerCase() || "";


    const sort =
        document.getElementById(
            "accountSort"
        )?.value || "default";


    if (gameFilter !== "all") {

        result =
            result.filter(
                account =>
                    account.game === gameFilter
            );

    }


    if (search) {

        result =
            result.filter(account =>

                (
                    account.name +
                    " " +
                    account.game +
                    " " +
                    account.level +
                    " " +
                    account.rank
                )
                .toLowerCase()
                .includes(search)

            );

    }


    if (sort === "low") {

        result.sort(
            (a,b) =>
                a.price - b.price
        );

    }


    if (sort === "high") {

        result.sort(
            (a,b) =>
                b.price - a.price
        );

    }


    if (!result.length) {

        grid.innerHTML = `

            <div class="empty-state"
                 style="grid-column:1/-1">

                <i class="fa-solid fa-gamepad"></i>

                <h3>
                    ${translations[currentLanguage].accounts}
                </h3>

                <p>
                    ${currentLanguage === "ar"
                        ? "لا توجد حسابات مطابقة للبحث."
                        : currentLanguage === "fr"
                            ? "Aucun compte ne correspond à votre recherche."
                            : "No accounts match your search."
                    }
                </p>

            </div>

        `;

        return;
    }


    grid.innerHTML =
        result.map(
            account =>
                createAccountCard(account)
        ).join("");

}


