-- DZ Game Market: mediator directory and multiple payment prices
-- Run in Supabase SQL Editor as the database owner (normally postgres).
-- Additive migration: preserves existing products and their current prices.

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS price_usd numeric(12,2),
  ADD COLUMN IF NOT EXISTS price_flexy numeric(12,2),
  ADD COLUMN IF NOT EXISTS supports_dzd boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS supports_usd boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS supports_flexy boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS public.mediators (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  image_url text,
  facebook_url text,
  whatsapp_url text,
  instagram_url text,
  tiktok_url text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.mediators ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON TABLE public.products TO anon, authenticated;
GRANT SELECT ON TABLE public.mediators TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.mediators TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.mediators_id_seq TO authenticated;

DROP POLICY IF EXISTS "Public can read active mediators" ON public.mediators;
CREATE POLICY "Public can read active mediators"
  ON public.mediators FOR SELECT TO anon, authenticated
  USING (is_active = true OR auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid);

DROP POLICY IF EXISTS "Admin can insert mediators" ON public.mediators;
CREATE POLICY "Admin can insert mediators"
  ON public.mediators FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid);

DROP POLICY IF EXISTS "Admin can update mediators" ON public.mediators;
CREATE POLICY "Admin can update mediators"
  ON public.mediators FOR UPDATE TO authenticated
  USING (auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid)
  WITH CHECK (auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid);

DROP POLICY IF EXISTS "Admin can delete mediators" ON public.mediators;
CREATE POLICY "Admin can delete mediators"
  ON public.mediators FOR DELETE TO authenticated
  USING (auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid);

