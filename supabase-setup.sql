create policy "Admin can update products" on public.products for update to authenticated using (auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid) with check (auth.uid() = '1e389dfb-a16b-438e-a1c8-4468bd308148'::uuid);
