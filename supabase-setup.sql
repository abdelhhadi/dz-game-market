
-- DZ Game Market catalog setup
-- Run this entire file in Supabase SQL Editor.
-- Admin UID is the one provided for this project.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('account','recharge')),
  game text not null,
  name text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  description text not null default '',
  image_url text,
  gallery_urls jsonb not null default '[]'::jsonb,
  seller_social jsonb not null default '[]'::jsonb,
  is_promotion boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.products add column if not exists category text;
alter table public.products add column if not exists game text;
alter table public.products add column if not exists name text;
alter table public.products add column if not exists price numeric(12,2) not null default 0;
alter table public.products add column if not exists description text not null default '';
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists gallery_urls jsonb not null default '[]'::jsonb;
alter table public.products add column if not exists seller_social jsonb not null default '[]'::jsonb;
alter table public.products add column if not exists is_promotion boolean not null default false;
alter table public.products add column if not exists is_active boolean not null default true;
alter table public.products add column if not exists created_at timestamptz not null default now();
alter table public.products add column if not exists updated_at timestamptz not null default now();

alter table public.products enable row level security;
drop policy if exists "Public can read active products" on public.products;
